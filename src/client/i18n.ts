export const DICTS: Record<string, Record<string, string>> = { zh, en }

export type Translate = (key: string, params?: Record<string, string | number>) => string

/** Translate without a host locale service (preview page, tests). */
export function localTranslate(locale: 'zh' | 'en'): Translate {
  const dict = DICTS[locale] ?? en
  return (key, params) => {
    let text = dict[key] ?? en[key] ?? key
    if (params !== undefined) for (const name of Object.keys(params)) text = text.replace(`{${name}}`, String(params[name]))
    return text
  }
}
